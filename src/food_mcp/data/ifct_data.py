def get_ifct_food(food_id: str) -> Optional[Dict[str, Any]]:
    """Retrieve an IFCT food profile by ID or canonical key."""
    key = food_id.lower().strip()
    if not key.startswith("ifct:"):
        key = f"ifct:{key}"
    return IFCT_DATABASE.get(key)


def search_ifct_foods(query: str, limit: int = 10) -> List[Dict[str, Any]]:
    """Search IFCT dataset by query matching English, scientific, and vernacular names."""
    q = query.lower().strip()
    if not q:
        return []

    tokens = q.split()
    results: List[tuple[int, Dict[str, Any]]] = []

    for fid, entry in IFCT_DATABASE.items():
        score = 0
        name = entry["name"].lower()
        sci = entry.get("scientific_name", "").lower()
        cat = entry.get("category", "").lower()
        vernaculars = [v.lower() for v in entry.get("vernacular_names", {}).values()]

        # Exact ID match
        if q == fid or q == fid.replace("ifct:", ""):
            score += 100

        # Exact title substring match
        if q in name:
            score += 50
        elif any(tok in name for tok in tokens):
            score += 25

        # Vernacular matches
        for vern in vernaculars:
            if q in vern:
                score += 40
            elif any(tok in vern for tok in tokens):
                score += 20

        # Scientific or category matches
        if q in sci:
            score += 30
        if q in cat:
            score += 15

        if score > 0:
            results.append((score, entry))

    results.sort(key=lambda x: x[0], reverse=True)
    return [item[1] for item in results[:limit]]


def list_ifct_foods() -> List[Dict[str, Any]]:
    """Return all IFCT food entries."""
    return list(IFCT_DATABASE.values())
