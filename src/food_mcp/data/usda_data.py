def get_usda_food(food_id: str) -> Optional[Dict[str, Any]]:
    """Retrieve a USDA food profile by ID."""
    key = food_id.lower().strip()
    if not key.startswith("usda:"):
        key = f"usda:{key}"
    return USDA_DATABASE.get(key)


def search_usda_foods(query: str, limit: int = 10) -> List[Dict[str, Any]]:
    """Search USDA dataset by food title or category."""
    q = query.lower().strip()
    if not q:
        return []

    tokens = q.split()
    results: List[tuple[int, Dict[str, Any]]] = []

    for fid, entry in USDA_DATABASE.items():
        score = 0
        name = entry["name"].lower()
        cat = entry.get("category", "").lower()

        if q == fid or q == fid.replace("usda:", ""):
            score += 100
        if q in name:
            score += 50
        elif any(tok in name for tok in tokens):
            score += 25
        if q in cat:
            score += 15

        if score > 0:
            results.append((score, entry))

    results.sort(key=lambda x: x[0], reverse=True)
    return [item[1] for item in results[:limit]]


def list_usda_foods() -> List[Dict[str, Any]]:
    """Return all USDA curated food entries."""
    return list(USDA_DATABASE.values())
